#!/usr/bin/env node
// Hermes cannot recover function source from release bytecode. Capture the
// self-contained page functions before native compilation instead.
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const root = path.resolve(__dirname, '..')
const input = path.join(root, 'utils/webview/injectedPolyfills.ts')
const output = path.join(root, 'utils/webview/injectedScriptSources.ts')
const compiled = ts.transpileModule(fs.readFileSync(input, 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS }
}).outputText
const ast = ts.createSourceFile('page.js', compiled, ts.ScriptTarget.ES2020, true, ts.ScriptKind.JS)
const names = ['injectedPolyfills']
const sources = names.map(name => {
  const matches = ast.statements.filter(node => ts.isFunctionDeclaration(node) && node.name?.text === name)
  if (matches.length !== 1) throw new Error('Expected one page function: ' + name)
  const source = matches[0].getText(ast)
  new Function('return (' + source + ')')
  return `export const ${name}Source = ${JSON.stringify(source)}\n`
})
const expected = '// Generated by scripts/generate-webview-sources.js. Do not edit.\n' + sources.join('\n')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected) {
    console.error('WebView sources are stale. Run node scripts/generate-webview-sources.js.')
    process.exit(1)
  }
  console.log('WebView source assets match their TypeScript input.')
} else fs.writeFileSync(output, expected)
